import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {TRIAL_LIMIT, runRealAITrial, trialStatus} from './nobi-ai-trial-control.mjs';
const {D1SQLite}=createRequire(import.meta.url)('/Users/shimizunaotomoo/Desktop/my-app/.claude/verify/d1-sqlite.js');
let checks=0;
const ok=(value,name)=>{assert(value,name);checks++;};
const now=Date.UTC(2026,9,12,3), db=new D1SQLite();
let calls=0;
const work=async signal=>{ok(!signal.aborted,'live abort signal');calls++;return {text:'fixture'};};
for(let i=1;i<=10;i++){const r=await runRealAITrial(db,work,now);ok(r.text==='fixture'&&r.trial.used===i,'count exactly one external attempt');}
ok(TRIAL_LIMIT===10,'hard trial cap');
ok((await runRealAITrial(db,work,now)).error==='ai_trial_daily'&&calls===10,'11th never reaches provider');
ok(!!db.get('ai-trial:notice:2026-10-12'),'notice persisted on tenth call');
ok((await runRealAITrial(db,work,now+86400000)).trial.used===1,'JST next-day reset');
const parallel=new D1SQLite();let release;
const hold=new Promise(resolve=>release=resolve);
const first=runRealAITrial(parallel,async()=>{await hold;return {text:'first'};},now);
await new Promise(resolve=>setTimeout(resolve,0));
const others=await Promise.all(Array.from({length:20},()=>runRealAITrial(parallel,()=>{throw Error('must not call');},now)));
ok(others.every(r=>r.error==='ai_busy'),'one global flight across twenty racers');
release();await first;ok((await trialStatus(parallel,now)).used===1,'concurrent refusals do not use quota');
const failures=new D1SQLite();
for(let i=1;i<=3;i++)ok((await runRealAITrial(failures,async()=>{throw Error('offline');},now)).trial.used===i,'unknown failures retain attempt count');
ok((await runRealAITrial(failures,work,now)).error==='ai_stopped','three errors stop before provider');
ok((await runRealAITrial(failures,work,now+86400000)).error==='ai_stopped','day reset does not reopen circuit');
ok((await trialStatus(failures,now)).stopped,'persisted circuit status');
const corrupt=new D1SQLite();corrupt.seed('ai-trial:day:2026-10-12','broken');
ok((await runRealAITrial(corrupt,work,now)).error==='ai_trial_daily','corrupt count refuses');
const lease=new D1SQLite();lease.seed('ai-trial:lease','old',now+1000);
ok((await runRealAITrial(lease,work,now)).error==='ai_busy','crashed worker lease remains enforced');
ok((await runRealAITrial(lease,work,now+1001)).text==='fixture','expired lease recovery');
ok(!lease.get('ai-trial:lease'),'own lease released');
const broken=new D1SQLite();broken.prepare=()=>{throw Error('storage offline');};
const before=calls;ok((await runRealAITrial(broken,work,now)).error==='ai_control_unavailable'&&calls===before,'storage failure never bypasses guard');
const recovery=new D1SQLite();await runRealAITrial(recovery,async()=>({error:'ai_failed'}),now);
await runRealAITrial(recovery,work,now);
ok(recovery.get('ai-trial:failures').v==='0','success clears consecutive error streak');
console.log('AI trial control: '+checks+' checks passed; in-memory SQLite, no network');
