def poem(g, y, parts, kigo=(), kire=(), lab=None, z=26):
    """五七五（七七）の区切りを、音の数つきの箱で示す。parts＝[(文字, 音の数)]"""
    while sum(width(p, z) + 34 for p, _ in parts) > W - 40 and z > 14: z -= 1
    tot = sum(width(p, z) + 34 for p, _ in parts); x = (W - tot) / 2
    if lab: g.text(lab, 30, y - 14, 18, COL['gray'], weight=700)
    for k, (p, n) in enumerate(parts):
        w = width(p, z) + 26; st, fl = (COL[c] for c in PAIRS[k % 4])
        g.rect(x, y, w, 56, fl, st, 3, r=10); g.text(p, x + w / 2, y + 37, z, None, 'middle')
        g.circle(x + w / 2, y + 76, 15, st); g.text(str(n), x + w / 2, y + 82, 17, '#fff', 'middle', 800)
        for kg in kigo:
            if kg in p: g.rect(x + 4, y + 50, w - 8, 5, COL['red'], None, r=2)
        x += w + 8

