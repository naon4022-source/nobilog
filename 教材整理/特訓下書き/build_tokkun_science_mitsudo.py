def rnd(x, places):
    q = Decimal(1).scaleb(-places)
    return (Decimal(x.numerator) / Decimal(x.denominator)).quantize(q, rounding=ROUND_HALF_UP)

def N(page, prompt, value, exact, places=None, expl=''):
    """value：書く答え（文字列）。exact：分数で計算した本当の値。places：四捨五入する桁（小数第何位まで）。"""
    v = Decimal(value)
    if places is None:
        assert Decimal(exact.numerator) / Decimal(exact.denominator) == v, (prompt, value, exact)
    else:
        assert rnd(exact, places) == v, (prompt, value, float(exact))
    ans = {'kind': 'number', 'value': value}
    u = infer_units(prompt)
    if u: ans['units'] = u  # 「71.68g」のように単位をつけても正解にする（ワークと同じ）
    Q.append(dict(page=page, prompt=prompt, answer=ans, explanation=expl))

