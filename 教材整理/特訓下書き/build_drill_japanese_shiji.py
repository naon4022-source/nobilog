TYPES = {'順接': ['順接'], '逆接': ['逆接'], '並列': ['並列', '累加', '並列・累加', '並列（累加）', '累加（並列）'],
         '対比': ['対比', '選択', '対比・選択', '対比（選択）', '選択（対比）'], '説明': ['説明', '補足', '説明・補足', '説明（補足）', '補足（説明）'],
         '転換': ['転換']}
TYPE_Q = '［　］の接続語の働きを、「順接・逆接・並列（累加）・対比（選択）・説明（補足）・転換」から選んで書こう。\n'
BLANK_Q = '（　）に入る接続語として最も適切なものを選ぼう。\n'
NEXT_Q = '次の文に続く内容として最も適切なものを選ぼう。\n'
INSTR = (TYPE_Q, BLANK_Q, NEXT_Q)
Q, T = [], []
cur = Q
def add(page, prompt, accepted, expl):
    cur.append(dict(page=page, prompt=prompt, answer={'kind': 'exact', 'accepted': accepted}, explanation=expl))
def typ(sent, kind, why):
    assert sent.count('［') == 1
    add(47, TYPE_Q + sent, TYPES[kind], f'{why}→{kind}。まちがえやすい点：前後の文だけを見て決める。接続語の「形」ではなく「前と後がどうつながっているか」で考える。')
_pos = [0]
def choose(page, head, body, opts, why):
    k = (_pos[0] * 3 + 1) % 4; _pos[0] += 1   # 正解の位置をずらす
    o = opts[1:]; o.insert(k, opts[0])
    lines = '　'.join(f'{LET[i]} {w}' for i, w in enumerate(o))
    add(page, head + body + '\n' + lines, [LET[k]], why)
def blank(body, opts, why): choose(47, BLANK_Q, body, opts, why)
def nxt(body, opts, why): choose(47, NEXT_Q, body, opts, why)
def nuki(passage, word, ans, why, ask='が指す内容'):
    assert passage.count(ans) == 1, ('書き抜きが本文に一か所ではない', ans)
    assert passage.count('〔') == 1
    n = len(ans)
    acc = [ans, '「' + ans + '」']
    if '、' in ans: acc += [ans.replace('、', ''), ans.replace('、', '・')]
    add(46, f'次の文章の〔{word}〕{ask}を、文章中から{n}字で書き抜こう。\n{passage}', acc,
        f'{why} 指す内容を〔{word}〕に置きかえて読み、文の意味が通るかを確かめる。')

