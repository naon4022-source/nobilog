def off(lon): return F(lon, 15)          # 標準時の、経度0度からのずれ（時間）。東経は＋、西経は−
def conv(t, lon_from, lon_to):            # ある地点の時刻を、別の地点の時刻に直す
    return t + dt.timedelta(hours=float(off(lon_to) - off(lon_from)))
def J(t, date=True):
    h = t.hour; ap = '午前' if h < 12 else '午後'; hh = h if h < 12 else h - 12
    m = f'{t.minute}分' if t.minute else ''
    core = f'{ap}{hh}時{m}'
    return (f'{t.month}月{t.day}日' if date else '') + core
def TA(t, date=True):
    a = J(t, date); out = [a, a.replace('午後0時', '正午')] if '午後0時' in a else [a]
    return out
