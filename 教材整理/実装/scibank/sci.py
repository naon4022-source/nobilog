"""理科1年（ワーク60枚・教科書=啓林館の写真51枚）の設定"""
from kbank import KUnit, spreads, ROOT
import functools

PAGES = spreads('理科ワーク')           # ワーク p2〜121（目視：k番目の写真が p(2+2k)〜p(3+2k)）
_TB = sorted(p.name for p in (ROOT / '理科の教科書').glob('S__*.jpg'))
def tbpage(p):
    """教科書の写真：k0〜20 が p2〜43、k21〜48 が p68〜123、k49 が p126〜127、k50 が p130〜131（目視で確認）。
    それ以外のページ（p44〜67、物質・エネルギーの本文）は写真が無いので参照しない。"""
    if 2 <= p <= 43: k = (p - 2) // 2
    elif 68 <= p <= 123: k = 21 + (p - 68) // 2
    elif p in (126, 127): k = 49
    elif p in (130, 131): k = 50
    else: raise AssertionError(f'教科書 p{p} の写真はありません')
    return '理科の教科書/' + _TB[k]

def unit(key, title, major, allowed, note):
    return KUnit(f'workbook-science-1-{key}', title, major, note, subject='理科', mode='workbook', book='理科ワーク',
                 pages=PAGES, allowed=allowed, tbfolder='理科の教科書', tbpage=tbpage)

