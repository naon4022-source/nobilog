def _pages(folder, left_map, single=()):
    pages, info = {}, {}
    for num, left in left_map.items():
        f = next((ROOTF / folder).glob(f'S__15982{num}*.jpg'))
        name = f'{folder}/{f.name}'
        ps = [left] if left in single else [left, left + 1]
        for p in ps: pages[p] = name
        info[name] = ps
    return pages, info

