"""特訓：円とおうぎ形の計量（教科書 p173〜176：円周・円の面積・おうぎ形の弧の長さと面積）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('circlecalc', '教科書 p173〜176（おうぎ形の弧の長さと面積）',
         '2026-10-08 Claude作成（特訓・下書き）。教科書 p173〜176 の円とおうぎ形の計量を、逆に求める・図形を組み合わせる・転がる円・時計の針などに広げた一段難しい問題。図はことばで説明している。'
         '答えは check.py で、π を文字として計算し直す方法と総当たりで検算。'
         '【保留】図を使わずに文章で正確に伝えられ、教科書問題と似ない問題は 20 問まで。70問にしていない。')
Q = [F(n, 10) for n in range(0, 7201)]

U.num('弧の長さが 6π cm、面積が 24π cm² のおうぎ形の半径を求めよう。', '8',
      '①おうぎ形の面積 ＝ 弧の長さ × 半径 ÷ 2（三角形のように考えられる）　②6π × r ÷ 2 ＝ 24π　③3r ＝ 24、r ＝ 8。答え 8cm',
      lambda: only(r for r in Q if r > 0 and 6 * r / 2 == 24 and (lambda a: F(a, 360) * 2 * r == 6)(F(6 * 360, 2) / r)), units=['cm'])
U.expr('面積が 36π cm² の円の周の長さを、π を使って答えよう（cm）。', '12π',
       '①πr² ＝ 36π より r ＝ 6　②円周 ＝ 2πr ＝ 12π　③答え 12π cm',
       lambda π: 2 * π * only(r for r in Q if r > 0 and r * r == 36))
U.expr('半径 6 cm、中心角 60° のおうぎ形の周の長さを、π を使って答えよう（cm）。', '2π+12',
       '①弧の長さ 2π × 6 × (60/360) ＝ 2π　②周 ＝ 弧 + 半径 2 本 ＝ 2π + 12　③答え 2π+12 cm',
       lambda π: 2 * π * 6 * F(60, 360) + 12, form='nosign')
U.expr('半径 12 cm の円から、中心角 90° のおうぎ形を切りとった残りの図形の面積を、π を使って答えよう（cm²）。', '108π',
       '①円の面積 144π　②残りは中心角 270° のおうぎ形：144π × (270/360)　③108π。答え 108π cm²',
       lambda π: π * 144 * F(270, 360))
U.expr('直径 16 cm の半円から、その直径上に並べた直径 8 cm の半円 2 つ（同じ側）を取りのぞいた図形の、周の長さを π を使って答えよう（cm）。', '16π',
       '①大きい半円の弧 ＝ 16π ÷ 2 ＝ 8π　②小さい半円の弧 ＝ 8π ÷ 2 ＝ 4π が 2 つ　③8π + 4π + 4π ＝ 16π（直線部分はない）。答え 16π cm',
       lambda π: π * 16 / 2 + 2 * (π * 8 / 2))
U.expr('1辺 10 cm の正方形 ABCD の中に、頂点Aを中心とする半径 10 cm のおうぎ形（中心角 90°）をかいた。正方形のうち、おうぎ形の外側の部分の面積を、π を使って答えよう（cm²）。', '100−25π',
       '①正方形 100　②おうぎ形 π × 10² × (90/360) ＝ 25π　③100 − 25π。答え 100−25π cm²',
       lambda π: 100 - π * 100 * F(90, 360), form='nosign')
U.expr('1辺 6 cm の正方形 ABCD の中に、頂点Aを中心とする半径 6 cm の 1/4 円と、頂点Cを中心とする半径 6 cm の 1/4 円をかいた。2つの 1/4 円が重なる部分の面積を、π を使って答えよう（cm²）。', '18π−36',
       '①1/4 円の面積 π × 36 ÷ 4 ＝ 9π　②2つの 1/4 円の和 18π は、正方形 36 に重なりの分を1回多く足したもの　③重なり ＝ 18π − 36。答え 18π−36 cm²',
       lambda π: 2 * (π * 36 / 4) - 36, form='nosign')
U.num('円の周の長さを 2 倍にすると、面積はもとの何倍になるか答えよう。', '4',
      '①周が 2 倍 → 半径が 2 倍　②面積は 半径 × 半径 に比例するので 2 × 2 ＝ 4 倍　③答え 4倍',
      lambda: only((F(2 * r) ** 2) / (F(r) ** 2) for r in (1, 3, 7)), units=['倍'])
U.num('おうぎ形の中心角を 2 倍にし、半径を半分にすると、面積はもとの何倍になるか答えよう。', '1/2',
      '①中心角 2 倍で面積 2 倍　②半径半分で面積 1/4 倍　③2 × (1/4) ＝ 1/2 倍。答え 1/2倍',
      lambda: only((F(r, 2) ** 2 * (2 * a)) / (F(r) ** 2 * a) for r, a in [(6, 30), (10, 45)]), units=['倍'])
U.expr('陸上競技のトラックは、長さ 100 m の直線 2 本と、半径 30 m の半円 2 つでできている。トラック1周の長さを、π を使って答えよう（m）。', '200+60π',
       '①直線 100 × 2 ＝ 200　②半円 2 つで円1つ分：2π × 30 ＝ 60π　③200 + 60π。答え 200+60π m',
       lambda π: 200 + 2 * π * 30, form='nosign')
U.num('円の面積（cm²）と円周の長さ（cm）が、同じ数になる円の半径を求めよう。', '2',
      '①πr² ＝ 2πr　②r ＝ 2（r は 0 でない）　③答え 2cm',
      lambda: only(r for r in Q if r > 0 and r * r == 2 * r), units=['cm'])
U.expr('時計の長針の長さは 12 cm である。長針の先が 20 分間に動く道のりを、π を使って答えよう（cm）。', '8π',
       '①20 分で長針は 360 × (20/60) ＝ 120 度回る　②2π × 12 × (120/360) ＝ 8π　③答え 8π cm',
       lambda π: 2 * π * 12 * F(20 * 6, 360))
U.expr('直径の比が 2：3 の2つの円がある。小さいほうの円の面積が 16π cm² のとき、大きいほうの円の面積を π を使って答えよう（cm²）。', '36π',
       '①小さい円の半径 4、大きい円の半径 6　②π × 6² ＝ 36π　③答え 36π cm²（面積の比は 4：9）',
       lambda π: π * (only(r for r in Q if r > 0 and r * r == 16) * F(3, 2)) ** 2)
U.expr('半径 3 cm の円が、1辺 10 cm の正方形の外側を、辺からはなれずにころがって1周する。円の中心が動いた長さを、π を使って答えよう（cm）。', '40+6π',
       '①辺にそって動く部分：10 × 4 ＝ 40　②かどでは中心が半径 3 cm、中心角 90° の弧をえがき、4 つ合わせて円1周分 2π × 3 ＝ 6π　③40 + 6π。答え 40+6π cm',
       lambda π: 10 * 4 + 4 * (2 * π * 3 * F(90, 360)), form='nosign')
U.expr('1辺 4 cm の正方形の4つの頂点を中心として、半径 2 cm の 1/4 円を正方形の内側に4つかいた。正方形のうち、4つの 1/4 円の外側の部分の面積を、π を使って答えよう（cm²）。', '16−4π',
       '①1/4 円 4 つで円1つ分：π × 2² ＝ 4π　②正方形 16　③16 − 4π。答え 16−4π cm²',
       lambda π: 16 - 4 * (π * 4 / 4), form='nosign')
U.num('おうぎ形の面積が、同じ半径の円の面積の 3/8 である。このおうぎ形の中心角を求めよう。', '135',
      '①中心角 ＝ 360 × (3/8)　②135 度　③答え 135度',
      lambda: only(a for a in Q if F(a, 360) == F(3, 8)), units=['度', '°'])
U.num('円周率を 3.14 として、半径 5 cm の円の面積を求めよう。', '78.5',
      '①面積 ＝ 半径 × 半径 × 円周率　②5 × 5 × 3.14 ＝ 78.5　③答え 78.5cm²',
      lambda: 5 * 5 * F(314, 100), units=['cm²'])
U.num('半径 6 cm で中心角 80° のおうぎ形と、半径 4 cm で中心角 x° のおうぎ形の面積が等しい。x の値を求めよう。', '180',
      '①π × 36 × (80/360) ＝ π × 16 × x/360　②36 × 80 ＝ 16x　③x ＝ 180。答え 180',
      lambda: only(x for x in Q if 36 * 80 == 16 * x))
U.num('弧の長さが半径の長さと等しいおうぎ形がある。このおうぎ形の面積は、半径を1辺とする正方形の面積の何倍か答えよう。', '1/2',
      '①おうぎ形の面積 ＝ 弧 × 半径 ÷ 2 ＝ r × r ÷ 2　②正方形の面積 r × r　③1/2 倍。答え 1/2倍',
      lambda: only((r * r / 2) / (r * r) for r in (F(1), F(5))), units=['倍'])
U.expr('半径 10 cm、中心角 72° のおうぎ形の面積から、弧の長さ（cm）の数の 5 倍をひいた値を、π を使って答えよう。', '0',
       '①面積 π × 100 × (72/360) ＝ 20π　②弧 2π × 10 × (72/360) ＝ 4π、5 倍で 20π　③20π − 20π ＝ 0。答え 0',
       lambda π: π * 100 * F(72, 360) - 5 * (2 * π * 10 * F(72, 360)), form='nosign')
