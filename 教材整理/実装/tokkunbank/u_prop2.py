      '①AB は x 軸に平行で長さ 5 − (−3) ＝ 8　②BC は y 軸に平行で長さ 2 − (−4) ＝ 6　③直角三角形なので 8 × 6 ÷ 2 ＝ 24。答え 24cm²',
