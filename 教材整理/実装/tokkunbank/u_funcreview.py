"""特訓：変化と対応 ふりかえりドリル（4章全体）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only, pt

U = Unit('funcreview', '教科書 p116〜143（4章 変化と対応 全体）',
         '2026-10-08 Claude作成（特訓・下書き）。比例と反比例を組み合わせる、入試の形の一段難しい問題（グラフの交点・図形の面積・変域）。'
         '答えは check.py で、座標の計算と総当たりで検算。'
         '【保留】4章のほかの小単元の特訓と重ならない総合問題は 13 問まで。70問にしていない。')
A = [F(n, 12) for n in range(-600, 601)]
def area(p, q, r):
    return abs((q[0] - p[0]) * (r[1] - p[1]) - (r[0] - p[0]) * (q[1] - p[1])) / F(2)

U.num('y は x に比例し、z は x に反比例する。x ＝ 2 のとき y ＝ 6、z ＝ 24 である。x が正の数で、y と z の値が等しくなる x を求めよう。', '4',
      '①y ＝ 3x、z ＝ 48/x　②3x ＝ 48/x より x × x ＝ 16　③x ＝ 4。答え 4',
      lambda: only(x for x in A if x > 0 and 3 * x == 48 / x))
U.num('比例 y ＝ 3x と反比例 y ＝ 12/x のグラフの交点のうち x 座標が正のものをA、反比例のグラフ上で x 座標が 4 の点をBとする。原点O、A、B を頂点とする三角形の面積を求めよう（1目もり 1 cm）。', '9',
      '①A(2, 6)、B(4, 3)　②かこむ長方形（横 4、縦 6）24 から、まわりの三角形 6、6、3 をひく　③24 − 15 ＝ 9。答え 9cm²',
      lambda: area((0, 0), (2, 6), (4, F(12, 4))), units=['cm²'])
U.coord('比例 y ＝ ax のグラフと反比例 y ＝ 18/x のグラフが点 (3, 6) で交わる。もう1つの交点の座標を答えよう。', ('-3', '-6'),
        '①a ＝ 2、2x ＝ 18/x より x × x ＝ 9　②x ＝ −3 のとき y ＝ −6　③答え (−3, −6)（原点について対称な点）',
        lambda: only(pt(x, 2 * x) for x in A if x != 0 and x != 3 and 2 * x == 18 / x))
U.num('反比例 y ＝ a/x（a ＞ 0）で、x の変域が 2 ≦ x ≦ 6 のとき、y の変域は b ≦ y ≦ 9 である。b の値を求めよう。', '3',
      '①a ＞ 0 なので、x が小さいほど y は大きい：x ＝ 2 で 9、a ＝ 18　②x ＝ 6 で y ＝ 3　③b ＝ 3。答え 3',
      lambda: only(F(a, 6) for a in range(1, 200) if F(a, 2) == 9))
U.num('反比例 y ＝ 12/x のグラフ上の点Pと原点Oを結ぶ線分のまん中の点Mは、Pがどこにあっても、ある反比例 y ＝ k/x のグラフ上にある。k の値を求めよう。', '3',
      '①P(a, 12/a) とすると M(a/2, 6/a)　②M の x 座標 × y 座標 ＝ (a/2) × (6/a) ＝ 3　③k ＝ 3。答え 3',
      lambda: only((a / 2) * (6 / a) for a in (F(1), F(4), F(-3))))
U.num('比例 y ＝ x/2 と反比例 y ＝ 8/x のグラフの交点のうち x 座標が正のものをPとし、Pから x 軸に垂線をひいた交点をHとする。三角形 OPH の面積を求めよう（1目もり 1 cm）。', '4',
      '①x/2 ＝ 8/x より x × x ＝ 16、x ＝ 4、P(4, 2)　②OH ＝ 4、PH ＝ 2　③4 × 2 ÷ 2 ＝ 4。答え 4cm²',
      lambda: only(area((0, 0), (x, x / 2), (x, 0)) for x in A if x > 0 and x / 2 == 8 / x), units=['cm²'])
U.num('x と y の値が、x ＝ 1、2、3、4、6 のとき y ＝ 24、12、8、6、4 と対応している。x ＝ 0.5 のときの y の値を求めよう。', '48',
      '①どの組も xy ＝ 24 で、y は x に反比例　②y ＝ 24/x　③x ＝ 0.5 で y ＝ 48。答え 48',
      lambda: only(F(24) / F(1, 2) for _ in [0] if all(x * y == 24 for x, y in [(1, 24), (2, 12), (3, 8), (4, 6), (6, 4)])))
U.num('反比例 y ＝ a/x（a ＜ 0）で、x が 2 から 4 にふえると、y は 3 ふえる。a の値を求めよう。', '-12',
      '①a/4 − a/2 ＝ 3　②−a/4 ＝ 3　③a ＝ −12（−6 から −3 へ 3 ふえる）。答え −12',
      lambda: only(a for a in range(-100, 0) if F(a, 4) - F(a, 2) == 3))
U.num('点A(2, 3)、点B(−4, −6) と原点Oがある。三角形 OAB の面積を求めよう（3点の位置に注意しよう）。', '0',
      '①A、B はどちらも比例のグラフ y ＝ 3x/2 の上にある（3/2 ＝ −6/(−4)）　②O、A、B は一直線上にあり、三角形はできない　③面積は 0。答え 0',
      lambda: area((0, 0), (2, 3), (-4, -6)))
U.num('反比例 xy ＝ 12 のグラフ上で、x 座標と y 座標がどちらも自然数である点のうち、x 座標と y 座標の和がもっとも小さくなる点の、その和を求めよう。', '7',
      '①自然数の組：(1, 12)、(2, 6)、(3, 4)、(4, 3)、(6, 2)、(12, 1)　②和は 13、8、7、7、8、13　③最小 7。答え 7',
      lambda: min(x + 12 // x for x in range(1, 13) if 12 % x == 0))
U.num('比例 y ＝ ax のグラフが、反比例 y ＝ 6/x のグラフと x 座標が 3 の点で交わる。このとき、比例のグラフ上で y 座標が 10 の点の x 座標を求めよう。', '15',
      '①交点 (3, 2)、a ＝ 2/3　②(2/3)x ＝ 10　③x ＝ 15。答え 15',
      lambda: only(x for x in A if F(2, 3) * x == 10))
U.num('反比例 y ＝ 24/x のグラフ上の2点 A(2, 12)、B(6, 4) がある。直線 AB 上で x 座標が 4 の点の y 座標と、反比例のグラフ上で x 座標が 4 の点の y 座標の差を求めよう。', '2',
      '①直線 AB：x が 4 ふえると y が 8 へるので、x ＝ 4 で y ＝ 8　②反比例上 x ＝ 4 で y ＝ 6　③8 − 6 ＝ 2。答え 2',
      lambda: (F(12) + (F(4) - 12) * F(4 - 2, 6 - 2)) - F(24, 4))
U.num('y は x に反比例し、そのグラフは点 (−2, 6) を通る。x の変域が 1 ≦ x ≦ 4 のとき、y のもっとも小さい値を求めよう。', '-12',
      '①比例定数 −12、y ＝ −12/x　②x ＞ 0 では y は負で、x が小さいほど y は小さい　③x ＝ 1 で −12。答え −12',
      lambda: min(F(-12) / x for x in A if 1 <= x <= 4))
