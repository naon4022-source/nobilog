"""特訓：比例の式①（教科書 p120〜122：比例・比例定数・変数が負の値をとるとき）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('prop1', '教科書 p120〜122（比例と比例定数）',
         '2026-10-08 Claude作成（特訓・下書き）。教科書 p120〜122 の比例・比例定数を、変化の量・2つの条件・変域から比例定数を求めるなどに広げた一段難しい問題。'
         '答えは check.py で、比例定数を総当たりで調べる方法で検算。'
         '【保留】比例の式の節は短く、教科書問題と似ない考え方の問題は 20 問まで。70問にしていない。')
A = [F(n, 60) for n in range(-1200, 1201)]

U.num('y は x に比例し、x の値が 3 ふえると y の値は 12 へる。比例定数を求めよう。', '-4',
      '①y ＝ ax で、x が 3 ふえると y は 3a ふえる　②3a ＝ −12　③a ＝ −4。答え −4',
      lambda: only(a for a in A if a * (5 + 3) - a * 5 == -12))
U.num('y は x に比例し、x ＝ 2 のときの y の値と、x ＝ 5 のときの y の値の和は 21 である。比例定数を求めよう。', '3',
      '①2a + 5a ＝ 21　②7a ＝ 21　③a ＝ 3。答え 3',
      lambda: only(a for a in A if 2 * a + 5 * a == 21))
U.pick('次のア〜オのうち、y が x に比例するものをすべて選び、記号で答えよう（x は 0 でないとする）。\nア y ＝ x/3\nイ y ＝ 3/x\nウ y ＝ 2x + 1\nエ xy ＝ 5\nオ y/x ＝ −2', 'アオ',
       '①比例は y ＝ ax の形　②ア y ＝ (1/3)x（○）　③オ y/x ＝ −2 は y ＝ −2x（○）　④イ・エは反比例、ウは + 1 があるので比例ではない　⑤答え ア、オ',
       lambda: {n for n, f in zip('アイウエオ', [lambda x: x / 3, lambda x: 3 / x, lambda x: 2 * x + 1, lambda x: 5 / x, lambda x: -2 * x]) if len({f(x) / x for x in (F(1), F(2), F(-5), F(7, 3))}) == 1})
U.num('y は x に比例し、x と y の和はいつも x の 4 倍になる。比例定数を求めよう。', '3',
      '①x + y ＝ 4x より y ＝ 3x　②比例定数 3　③答え 3',
      lambda: only(a for a in A if all(x + a * x == 4 * x for x in (1, 2, 5))))
U.num('y は x に比例し、x ＝ a のとき y ＝ 8、x ＝ a + 3 のとき y ＝ 20 である。a の値を求めよう。', '2',
      '①x が 3 ふえると y は 12 ふえるので、比例定数は 4　②4a ＝ 8　③a ＝ 2。答え 2',
      lambda: only(a for a in A for k in A if k * a == 8 and k * (a + 3) == 20))
U.num('y は x に比例し、x ＝ 6 のとき y ＝ −4 である。y の値が x の値より 10 大きくなるときの x の値を求めよう。', '-6',
      '①y ＝ −2x/3　②−2x/3 ＝ x + 10　③−5x/3 ＝ 10、x ＝ −6（y ＝ 4）。答え −6',
      lambda: only(x for x in A if F(-4, 6) * x == x + 10))
U.num('y ＝ ax（a ＞ 0）が、x ＝ 2 のとき y ＝ b、x ＝ b のとき y ＝ 18 となる。a の値を求めよう。', '3',
      '①b ＝ 2a　②a × b ＝ 18 より a × 2a ＝ 18、a × a ＝ 9　③a ＞ 0 なので a ＝ 3。答え 3',
      lambda: only(a for a in A if a > 0 and a * (2 * a) == 18))
U.num('y は x に比例し、y ＝ 2z である。x ＝ 3 のとき z ＝ 4 になる。z を x の式で表したときの比例定数を求めよう。', '4/3',
      '①z が x に比例し、x ＝ 3 で z ＝ 4 なので z ＝ (4/3)x　②（y ＝ 2z ＝ (8/3)x も x に比例）　③答え 4/3',
      lambda: only(k for k in A if k * 3 == 4))
U.expr('円の半径を x cm、周の長さを y cm とすると、y は x に比例する。比例定数を、π を使って答えよう。', '2π',
       '①y ＝ 2πx　②比例定数は 2π　③答え 2π',
       lambda π: 2 * π)
U.num('y は x に比例し、x ＝ −3 のとき y ＝ 7.5、x ＝ 2 のとき y ＝ □、x ＝ △ のとき y ＝ −10 である。□ と △ の和を求めよう。', '-1',
      '①比例定数 7.5 ÷ (−3) ＝ −2.5　②□ ＝ (−2.5) × 2 ＝ −5、△ ＝ (−10) ÷ (−2.5) ＝ 4　③−5 + 4 ＝ −1。答え −1',
      lambda: (lambda a: a * 2 + only(x for x in A if a * x == -10))(F(15, 2) / -3))
U.num('y ＝ ax で、x の変域が −2 ≦ x ≦ 3 のとき、y の変域は −9 ≦ y ≦ 6 である。a の値を求めよう。', '-3',
      '①a が正なら x ＝ 3 で最大になるが 3a ＝ 6 だと x ＝ −2 で −4 になり合わない　②a が負なら x ＝ 3 で最小：3a ＝ −9、a ＝ −3　③x ＝ −2 で 6 も合う。答え −3',
      lambda: only(a for a in A if min(a * -2, a * 3) == -9 and max(a * -2, a * 3) == 6))
U.num('y は x に比例し、x ＝ 4 のとき y ＝ −6 である。x の変域が −4 ≦ x ≦ 2 のとき、y のもっとも大きい値を求めよう。', '6',
      '①y ＝ −3x/2（x が大きいほど y は小さい）　②もっとも大きいのは x ＝ −4 のとき：6　③答え 6',
      lambda: max(F(-6, 4) * x for x in A if -4 <= x <= 2))
U.num('y ＝ ax で、x ＝ −3 のときと x ＝ 5 のときの y の値の差（x ＝ 5 のとき − x ＝ −3 のとき）が −24 である。a の値を求めよう。', '-3',
      '①5a − (−3a) ＝ 8a　②8a ＝ −24　③a ＝ −3。答え −3',
      lambda: only(a for a in A if a * 5 - a * -3 == -24))
U.num('y は x に比例し、x の値が 1.5 ふえると y の値は 4 ふえる。x ＝ −3 のときの y の値を求めよう。', '-8',
      '①比例定数 4 ÷ 1.5 ＝ 8/3　②y ＝ (8/3) × (−3)　③y ＝ −8。答え −8',
      lambda: only(a * -3 for a in A if a * F(3, 2) == 4))
U.num('2つの比例 y ＝ 4x と y ＝ −x/2 で、x ＝ 6 のときの y の値の差（大きいほう − 小さいほう）を求めよう。', '27',
      '①y ＝ 4 × 6 ＝ 24　②y ＝ −6/2 ＝ −3　③24 − (−3) ＝ 27。答え 27',
      lambda: abs(4 * 6 - F(-6, 2)))
U.num('y は x に比例し、対応する x と y の値の積が 18 になるのは x ＝ 3 のときである。比例定数を求めよう。', '2',
      '①x ＝ 3 のとき xy ＝ 18 なので y ＝ 6　②比例定数 6 ÷ 3 ＝ 2　③答え 2',
      lambda: only(a for a in A if 3 * (a * 3) == 18))
U.pick('次のア〜エのうち、y が x に比例するものをすべて選び、記号で答えよう。\nア 正方形の1辺の長さ x cm と周の長さ y cm\nイ 周の長さが 20 cm の長方形の縦 x cm と横 y cm\nウ 円の半径 x cm と面積 y cm²\nエ 時速 40 km で走るときの時間 x 時間と道のり y km', 'アエ',
       '①ア y ＝ 4x（○）　②イ y ＝ 10 − x（比例ではない）　③ウ y ＝ πx²（比例ではない）　④エ y ＝ 40x（○）　⑤答え ア、エ',
       lambda: {n for n, f in zip('アイウエ', [lambda x: 4 * x, lambda x: 10 - x, lambda x: 3 * x * x, lambda x: 40 * x]) if len({f(x) / x for x in (F(1), F(2), F(3))}) == 1})
U.num('y は x に比例し、x ＝ 5 のとき、y の値は x の値より 6 小さい。x ＝ −10 のときの y の値を求めよう。', '2',
      '①x ＝ 5 のとき y ＝ −1 なので、比例定数 −1/5　②y ＝ (−1/5) × (−10)　③y ＝ 2。答え 2',
      lambda: only(a * -10 for a in A if a * 5 == 5 - 6))
U.num('2つの比例 y ＝ 2x と y ＝ −3x で、x 座標が同じ2点の y の値の差が 15 になる。x が正の数のとき、x の値を求めよう。', '3',
      '①2x − (−3x) ＝ 5x　②5x ＝ 15　③x ＝ 3。答え 3',
      lambda: only(x for x in A if x > 0 and 2 * x - (-3 * x) == 15))
U.num('y は x に比例する。x ＝ 4 のときの y の値は、x ＝ −2 のときの y の値より 9 小さい。比例定数を求めよう。', '-3/2',
      '①4a ＝ −2a − 9　②6a ＝ −9　③a ＝ −3/2。答え −3/2',
      lambda: only(a for a in A if 4 * a == -2 * a - 9))
