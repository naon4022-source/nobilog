"""特訓：立体の体積（教科書 p204〜207）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('volume', '教科書 p204〜207（角柱・円柱・角錐・円錐・球の体積）',
         '2026-10-08 Claude作成（特訓・下書き）。体積を逆に求める・くりぬく・切り取る・水位の変化などに広げた一段難しい問題。答えは check.py で、π を文字として計算し直して検算。'
         '【保留】図なしで伝えられ、教科書問題と似ない問題は 10 問まで。70問にしていない。')
Q = [F(n, 10) for n in range(0, 5001)]

U.num('立方体の表面積が 150 cm² のとき、体積を求めよう。', '125',
      '①1つの面は 150 ÷ 6 ＝ 25 cm²、1辺 5 cm　②5 × 5 × 5 ＝ 125　③答え 125cm³',
      lambda: only(a ** 3 for a in Q if a > 0 and 6 * a * a == 150), units=['cm³'])
U.num('底面の半径が 3 cm、高さが 8 cm の円柱と、同じ体積で底面の半径が 3 cm の円錐がある。円錐の高さを求めよう。', '24',
      '①円錐の体積は、底面と高さが同じ円柱の 1/3　②同じ体積にするには高さを 3 倍に　③8 × 3 ＝ 24。答え 24cm',
      lambda: only(h for h in Q if F(1, 3) * 9 * h == 9 * 8), units=['cm'])
U.num('体積が 36π cm³ の球の半径を求めよう。', '3',
      '①4πr³/3 ＝ 36π　②r³ ＝ 27　③r ＝ 3。答え 3cm',
      lambda: only(r for r in Q if r > 0 and F(4, 3) * r ** 3 == 36), units=['cm'])
U.num('半径 r の球の体積は、底面の半径が r、高さが 2r の円柱の体積の何倍か答えよう。', '2/3',
      '①球 4πr³/3、円柱 πr² × 2r ＝ 2πr³　②(4/3) ÷ 2 ＝ 2/3　③答え 2/3倍',
      lambda: only((F(4, 3) * r ** 3) / (r * r * 2 * r) for r in (F(1), F(3))), units=['倍'])
U.num('1辺 6 cm の立方体から、1つの頂点に集まる3つの辺のまん中の点を通る平面で、小さな三角錐を切り取った。切り取った三角錐の体積を求めよう。', '4.5',
      '①三角錐は、直角をはさむ2辺 3 cm の直角三角形を底面、高さ 3 cm　②底面積 3 × 3 ÷ 2 ＝ 4.5　③4.5 × 3 ÷ 3 ＝ 4.5。答え 4.5cm³',
      lambda: F(1, 3) * (F(3 * 3, 2)) * 3, units=['cm³'])
U.num('底面の半径が 4 cm の円柱の容器に水が入っている。この中に半径 2 cm の鉄の球を完全に沈めると、水面は何 cm 上がるか答えよう（水はあふれない）。', '2/3',
      '①球の体積 4π × (8/3) ＝ 32π/3　②水面の上がる高さ × 底面積 16π ＝ 32π/3　③高さ ＝ 2/3。答え 2/3cm',
      lambda: (F(4, 3) * 8) / 16, units=['cm'])
U.num('底面が1辺 6 cm の正方形の正四角錐の体積が 96 cm³ である。高さを求めよう。', '8',
      '①36 × h ÷ 3 ＝ 96　②12h ＝ 96　③h ＝ 8。答え 8cm',
      lambda: only(h for h in Q if F(36, 3) * h == 96), units=['cm'])
U.num('立方体の1つの面を底面とし、向かい合う面の中心を頂点とする四角錐をつくる。この四角錐の体積は、立方体の体積の何倍か答えよう。', '1/3',
      '①底面は立方体の面と同じ、高さは立方体の1辺と同じ　②角錐の体積は (底面積 × 高さ)/3　③1/3 倍。答え 1/3倍',
      lambda: only((F(1, 3) * a * a * a) / (a ** 3) for a in (F(2), F(5))), units=['倍'])
U.expr('底面の半径 3 cm、高さ 6 cm の円柱から、同じ底面で高さ 6 cm の円錐をくりぬいた立体の体積を、π を使って答えよう（cm³）。', '36π',
       '①円柱 π × 9 × 6 ＝ 54π　②円錐 54π ÷ 3 ＝ 18π　③54π − 18π ＝ 36π。答え 36π cm³',
       lambda π: π * 9 * 6 - π * 9 * 6 / 3)
U.num('縦 20 cm、横 30 cm の直方体の容器に 4.8 L の水を入れると、水の深さは何 cm になるか答えよう。', '8',
      '①4.8 L ＝ 4800 cm³　②底面積 600 cm²　③4800 ÷ 600 ＝ 8。答え 8cm',
      lambda: F(4800, 20 * 30), units=['cm'])
