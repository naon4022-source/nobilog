"""特訓：比と比例式（教科書 p100〜101：比の値・比例式の性質・比例式を解く）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('ratio', '教科書 p100〜101（比の値・比例式）',
         '2026-10-08 Claude作成（特訓・下書き）。教科書 p100〜101 の比の値・比例式の性質を、文字の比・比どうしの関係・同じ数をたしたときの比などに広げた一段難しい問題。'
         '答えは check.py で総当たりにより検算。'
         '【保留】比と比例式の節は短く、教科書問題（比例式を解く・比の値を求める）と似ない考え方の問題は 26 問まで。比例式の数字を替えて増やすと水増しになるため、70問にしていない。')
D = [F(n, 60) for n in range(-3600, 3601)]
Z = range(-200, 201)

U.num('x：y ＝ 3：5 のとき、(2x + y)：(x + 3y) の比の値を求めよう。', '11/18',
      '①x ＝ 3k、y ＝ 5k とする　②2x + y ＝ 11k、x + 3y ＝ 18k　③比の値 11/18。答え 11/18',
      lambda: only(F(2 * x + y, x + 3 * y) for x, y in [(3, 5), (6, 10), (9, 15)]))
U.num('a：b ＝ 2：3、b：c ＝ 5：4 のとき、a：c の比の値を求めよう。', '5/6',
      '①b を 15 にそろえる：a：b ＝ 10：15、b：c ＝ 15：12　②a：c ＝ 10：12　③比の値 10/12 ＝ 5/6。答え 5/6',
      lambda: F(2, 3) * F(5, 4))
U.num('比例式 (x + 2)：(x − 1) ＝ 5：2 を満たす x を求めよう。', '3',
      '①比例式の性質（外側の積 ＝ 内側の積）：2(x + 2) ＝ 5(x − 1)　②2x + 4 ＝ 5x − 5　③x ＝ 3。答え 3',
      lambda: only(x for x in D if 2 * (x + 2) == 5 * (x - 1)))
U.num('比例式 (2x − 1)：3 ＝ (x + 4)：2 を満たす x を求めよう。', '14',
      '①2(2x − 1) ＝ 3(x + 4)　②4x − 2 ＝ 3x + 12　③x ＝ 14。答え 14',
      lambda: only(x for x in D if 2 * (2 * x - 1) == 3 * (x + 4)))
U.num('3：x ＝ x：12 を満たす正の数 x を求めよう。', '6',
      '①x × x ＝ 3 × 12 ＝ 36　②正の数なので x ＝ 6　③答え 6',
      lambda: only(x for x in D if x > 0 and x * x == 36))
U.num('比の値が 0.75 で、和が 35 になる2つの数がある。小さいほうの数を答えよう。', '15',
      '①0.75 ＝ 3/4 なので、2つの数の比は 3：4　②3k + 4k ＝ 35、k ＝ 5　③小さいほう 15。答え 15',
      lambda: only(a for a in D for b in [35 - a] if b != 0 and a / b == F(3, 4)))
U.num('比 (2/3)：(5/6) の比の値を求めよう。', '4/5',
      '①比の値 ＝ 前の数 ÷ 後の数 ＝ (2/3) ÷ (5/6)　②(2/3) × (6/5) ＝ 4/5　③答え 4/5',
      lambda: F(2, 3) / F(5, 6))
U.num('x：3 ＝ 4：y となる自然数 x、y の組は何組あるか答えよう。', '6',
      '①比例式の性質より xy ＝ 12　②(x, y) ＝ (1, 12)、(2, 6)、(3, 4)、(4, 3)、(6, 2)、(12, 1)　③6 組。答え 6組',
      lambda: sum(1 for x in range(1, 50) for y in range(1, 50) if x * y == 3 * 4), units=['組'])
U.pick('2：3 と比の値が等しい比を、次のア〜エからすべて選び、記号で答えよう。\nア 4：6\nイ 0.6：0.9\nウ (1/2)：(3/4)\nエ 8：10', 'アイウ',
       '①比の値 2/3 になるかを調べる　②ア 4/6 ＝ 2/3、イ 0.6/0.9 ＝ 2/3、ウ (1/2) ÷ (3/4) ＝ 2/3、エ 8/10 ＝ 4/5　③答え ア、イ、ウ',
       lambda: {n for n, v in zip('アイウエ', [F(4, 6), F(6, 9), F(1, 2) / F(3, 4), F(8, 10)]) if v == F(2, 3)})
U.num('x：6 ＝ 6：9 を満たす x を求めよう。', '4',
      '①9x ＝ 36　②x ＝ 4　③答え 4（4、6、9 は、となりどうしの比が等しい並び）',
      lambda: only(x for x in D if 9 * x == 36))
U.num('a：b ＝ 5：3 のとき、(a − b) ÷ (a + b) の値を求めよう。', '1/4',
      '①a ＝ 5k、b ＝ 3k　②(5k − 3k)/(5k + 3k) ＝ 2k/8k　③1/4。答え 1/4',
      lambda: only(F(a - b, a + b) for a, b in [(5, 3), (10, 6), (15, 9)]))
U.num('比例式 x：4 ＝ 9：x を満たす負の数 x を求めよう。', '-6',
      '①x × x ＝ 36　②x ＝ 6 か −6　③負の数は −6。答え −6',
      lambda: only(x for x in D if x < 0 and x * x == 36))
U.num('x：y ＝ 3：4 で、y：6 ＝ 2：3 である。x の値を求めよう。', '3',
      '①y：6 ＝ 2：3 より 3y ＝ 12、y ＝ 4　②x：4 ＝ 3：4 より x ＝ 3　③答え 3',
      lambda: only(x for x in D for y in [F(12, 3)] if 4 * x == 3 * y))
U.num('比 a：b で、a を 2 倍、b を 3 倍すると、比が 1：1 になる。もとの比 a：b の比の値を求めよう。', '3/2',
      '①2a ＝ 3b　②a/b ＝ 3/2　③答え 3/2',
      lambda: only(F(a, b) for a in range(1, 30) for b in range(1, 30) if 2 * a == 3 * b))
U.num('比 x：(x + 5) の比の値が 2/3 になる x を求めよう。', '10',
      '①3x ＝ 2(x + 5)　②x ＝ 10　③確かめ：10：15 ＝ 2：3。答え 10',
      lambda: only(x for x in D if 3 * x == 2 * (x + 5)))
U.num('x：y ＝ 5：2 で、x − y ＝ 12 である。x + y の値を求めよう。', '28',
      '①x ＝ 5k、y ＝ 2k、差 3k ＝ 12、k ＝ 4　②x + y ＝ 7k ＝ 28　③答え 28',
      lambda: only(x + y for x in Z for y in Z if 2 * x == 5 * y and x - y == 12))
U.num('比例式 0.2：x ＝ 0.5：3 を満たす x を求めよう。', '1.2',
      '①0.5x ＝ 0.2 × 3 ＝ 0.6　②x ＝ 1.2　③答え 1.2',
      lambda: only(x for x in D if F(1, 2) * x == F(1, 5) * 3))
U.num('比例式 (1/2)：(1/3) ＝ x：(x − 1) を満たす x を求めよう。', '3',
      '①(1/2)(x − 1) ＝ (1/3)x　②6 倍：3(x − 1) ＝ 2x　③x ＝ 3。答え 3',
      lambda: only(x for x in D if F(1, 2) * (x - 1) == F(1, 3) * x))
U.choice('3つの比 ア 3：5、イ 5：8、ウ 7：11 のうち、比の値がもっとも大きいものを選び、記号で答えよう。\nア 3：5\nイ 5：8\nウ 7：11', 'ウ',
         '①比の値：3/5 ＝ 0.6、5/8 ＝ 0.625、7/11 ＝ 0.636…　②もっとも大きいのはウ　③答え ウ',
         lambda: max(zip([F(3, 5), F(5, 8), F(7, 11)], 'アイウ'))[1])
U.num('比例式 4：(x − 2) ＝ □：3 の解が x ＝ 6 になるように、□ にあてはまる数を答えよう。', '3',
      '①x ＝ 6 を入れると 4：4 ＝ □：3　②4 × 3 ＝ 4 × □　③□ ＝ 3。答え 3',
      lambda: only(c for c in D if 4 * 3 == (6 - 2) * c))
U.num('18 を、x と 18 − x の2つに分けて、x：(18 − x) ＝ 4：5 にしたい。x の値を答えよう。', '8',
      '①5x ＝ 4(18 − x)　②9x ＝ 72　③x ＝ 8。答え 8',
      lambda: only(x for x in D if 5 * x == 4 * (18 - x)))
U.num('2つの数 x、y の比が 3：4 で、2つの数の平均が 21 である。x の値を答えよう。', '18',
      '①x + y ＝ 42、x ＝ 3k、y ＝ 4k　②7k ＝ 42、k ＝ 6　③x ＝ 18。答え 18',
      lambda: only(x for x in Z for y in Z if 4 * x == 3 * y and x + y == 42))
U.num('a：b ＝ 1：2、b：c ＝ 3：4、c：d ＝ 5：6 のとき、a：d の比の値を求めよう。', '5/16',
      '①a/d ＝ (a/b) × (b/c) × (c/d)　②(1/2) × (3/4) × (5/6) ＝ 15/48　③5/16。答え 5/16',
      lambda: F(1, 2) * F(3, 4) * F(5, 6))
U.num('比 2：3 の前の数と後の数の両方に同じ数をたしたら、比が 5：6 になった。たした数を答えよう。', '3',
      '①(2 + x)：(3 + x) ＝ 5：6　②6(2 + x) ＝ 5(3 + x)　③12 + 6x ＝ 15 + 5x、x ＝ 3。答え 3',
      lambda: only(x for x in D if 6 * (2 + x) == 5 * (3 + x)))
U.num('x：y ＝ 3：2 のとき、x²：y² の比の値を求めよう。', '9/4',
      '①x ＝ 3k、y ＝ 2k　②x² ＝ 9k²、y² ＝ 4k²　③比の値 9/4。答え 9/4',
      lambda: only(F(x * x, y * y) for x, y in [(3, 2), (6, 4), (15, 10)]))
U.num('a：b：c ＝ 2：3：4 のとき、(a + c)：(b + c) の比の値を求めよう。', '6/7',
      '①a ＝ 2k、b ＝ 3k、c ＝ 4k　②a + c ＝ 6k、b + c ＝ 7k　③6/7。答え 6/7',
      lambda: only(F(a + c, b + c) for a, b, c in [(2, 3, 4), (4, 6, 8)]))
