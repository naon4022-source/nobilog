"""特訓：反比例のグラフ（教科書 p134〜138）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only, pt

U = Unit('invgraph', '教科書 p134〜138（反比例のグラフ）',
         '2026-10-08 Claude作成（特訓・下書き）。教科書 p134〜138 の反比例のグラフを、グラフ上の点がつくる長方形や三角形、比例のグラフとの交点などに広げた一段難しい問題。'
         '答えは check.py で、座標を使った計算と総当たりで検算。'
         '【保留】反比例のグラフで、教科書問題（通る点・格子点・式）と似ない考え方の問題は 12 問まで。70問にしていない。')
A = [F(n, 12) for n in range(-600, 601)]
def area(p, q, r):
    return abs((q[0] - p[0]) * (r[1] - p[1]) - (r[0] - p[0]) * (q[1] - p[1])) / F(2)

U.num('y ＝ 12/x のグラフ上の点P（x ＞ 0）から x 軸と y 軸にそれぞれ垂線をひいてできる長方形（原点をふくむ）の面積は、Pの位置によらず同じである。その面積を求めよう。', '12',
      '①P(a, 12/a) とすると、長方形の縦 12/a、横 a　②面積 a × 12/a ＝ 12　③答え 12',
      lambda: only(a * (12 / a) for a in (F(1), F(3), F(5, 2))))
U.num('反比例のグラフが点 P(2, 3) と点 Q(−1, b) を通る。b の値を求めよう。', '-6',
      '①比例定数 2 × 3 ＝ 6　②−1 × b ＝ 6　③b ＝ −6。答え −6',
      lambda: only(b for b in A if -1 * b == 2 * 3))
U.coord('y ＝ 2x のグラフと y ＝ 8/x のグラフの交点のうち、x 座標が正のものの座標を答えよう。', ('2', '4'),
        '①2x ＝ 8/x より x × x ＝ 4　②x ＞ 0 なので x ＝ 2　③y ＝ 4 で (2, 4)。答え (2, 4)',
        lambda: only(pt(x, 2 * x) for x in A if x > 0 and 2 * x == 8 / x))
U.num('y ＝ ax のグラフと y ＝ 18/x のグラフの交点の x 座標の1つが 3 である。a の値を求めよう。', '2',
      '①交点は y ＝ 18/3 ＝ 6 で (3, 6)　②y ＝ ax が (3, 6) を通る：3a ＝ 6　③a ＝ 2。答え 2',
      lambda: only(a for a in A if a * 3 == F(18, 3)))
U.num('反比例のグラフが点 A(3, 4) を通る。このグラフ上で x 座標が 6 の点をBとする。原点O、A、B を頂点とする三角形の面積を求めよう（1目もり 1 cm）。', '9',
      '①比例定数 12、B(6, 2)　②O、A、B をかこむ長方形（横 6、縦 4）24 から、まわりの三角形 6、6、3 をひく　③24 − 15 ＝ 9。答え 9cm²',
      lambda: area((0, 0), (3, 4), (6, F(12, 6))), units=['cm²'])
U.num('y ＝ 8/x のグラフ上の2点 A(1, 8)、B(4, 2) と原点Oを頂点とする三角形の面積を求めよう（1目もり 1 cm）。', '15',
      '①かこむ長方形（横 4、縦 8）32 から、まわりの三角形をひく　②1 × 8 ÷ 2 ＝ 4、4 × 2 ÷ 2 ＝ 4、3 × 6 ÷ 2 ＝ 9　③32 − 17 ＝ 15。答え 15cm²',
      lambda: area((0, 0), (1, 8), (4, 2)), units=['cm²'])
U.num('反比例 y ＝ 12/x のグラフと、比例 y ＝ 3x のグラフの交点はいくつあるか答えよう。', '2',
      '①3x ＝ 12/x より x × x ＝ 4　②x ＝ 2 と x ＝ −2 の2つ（(2, 6) と (−2, −6)）　③答え 2個',
      lambda: sum(1 for x in A if x != 0 and 3 * x == 12 / x), units=['個'])
U.choice('反比例 y ＝ −6/x で、x ＞ 0 の範囲で x の値がふえると、y の値はどうなるか。次のア・イから選び、記号で答えよう。\nア ふえる\nイ へる', 'ア',
         '①x ＝ 1 で −6、x ＝ 2 で −3、x ＝ 3 で −2　②負の数が 0 に近づくので、y はふえる　③答え ア',
         lambda: 'ア' if all(F(-6) / (x + 1) > F(-6) / x for x in range(1, 20)) else 'イ')
U.coord('y ＝ 12/x のグラフ上の点で、x 座標が y 座標より 1 大きく、x ＞ 0 である点の座標を答えよう。', ('4', '3'),
        '①x × (x − 1) ＝ 12 となる正の数をさがす　②x ＝ 4 なら 4 × 3 ＝ 12　③点 (4, 3)。答え (4, 3)',
        lambda: only(pt(x, 12 / x) for x in A if x > 0 and x - 12 / x == 1))
U.num('y ＝ a/x のグラフと y ＝ −2x のグラフの交点の1つが (−3, b) である。a の値を求めよう。', '-18',
      '①y ＝ −2x に x ＝ −3 を入れて b ＝ 6　②a ＝ xy ＝ (−3) × 6　③a ＝ −18。答え −18',
      lambda: only(a for a in A if F(a) == -3 * (-2 * -3)))
U.coord('y ＝ 24/x のグラフ上の点Pで、x 座標が y 座標の 6 倍であり、x ＞ 0 である点の座標を答えよう。', ('12', '2'),
        '①x ＝ 6y として xy ＝ 6y × y ＝ 24　②y × y ＝ 4、y ＝ 2（正）　③x ＝ 12 で (12, 2)。答え (12, 2)',
        lambda: only(pt(6 * y, y) for y in A if y > 0 and 6 * y * y == 24))
U.num('反比例のグラフが点 (2, 9) を通る。このグラフ上の点のうち、x 座標と y 座標がどちらも自然数である点は何個あるか答えよう。', '6',
      '①比例定数 18、xy ＝ 18　②x は 18 の約数：1、2、3、6、9、18　③6 個。答え 6個',
      lambda: sum(1 for x in range(1, 19) if 18 % x == 0), units=['個'])
