def arcpts(c, r, d1, d2, n=72): return [(c[0] + r * math.cos(math.radians(d1 + (d2 - d1) * i / n)), c[1] + r * math.sin(math.radians(d1 + (d2 - d1) * i / n))) for i in range(n + 1)]
def mc_area(inside, x0, x1, y0, y1, n=600):
    """図の部分の面積を、細かい方眼で数えて近似（π の式の答えを別の方法で点検する）"""
    hx, hy = (x1 - x0) / n, (y1 - y0) / n
    return sum(1 for i in range(n) for j in range(n) if inside(x0 + (i + .5) * hx, y0 + (j + .5) * hy)) * hx * hy
def approx(expr_val, num, tol=0.02): return abs(expr_val - num) <= tol * max(1, abs(num))

