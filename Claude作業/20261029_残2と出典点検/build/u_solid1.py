def paths(edges, a, b, k):
    adj = {}
    for x, y in edges: adj.setdefault(x, set()).add(y); adj.setdefault(y, set()).add(x)
    def go(p, n): return (1 if p == b else 0) if n == 0 else sum(go(q, n - 1) for q in adj[p])
    return go(a, k)
