def near(x):
    f = F(x).limit_denominator(1000)
    assert abs(float(f) - x) < 1e-9, x
    return f


def per(xs):
    """答えの書き方（順番・区切り）のゆれ"""
    from itertools import permutations
    out = []
    for p in permutations(xs):
        for sep in ('、', ',', '・', ' ', 'と'):
            out.append(sep.join(p))
    return out


def fold_vertices(cells):
    """立方体の展開図を方眼の上で折りたたむ（立方体をころがす）模型。展開図のかどの点 → 立方体の頂点（0/1 の座標）"""
    S = set(cells); mp = {}; seen = set()
    def T(pos, c, d):
        cx, cy = c; out = {}
        for v, (x, y, z) in pos.items():
            if d == (1, 0): out[v] = (cx + 1 + z, y, -(x - (cx + 1)))
            if d == (-1, 0): out[v] = (cx - z, y, x - cx)
            if d == (0, 1): out[v] = (x, cy + 1 + z, -(y - (cy + 1)))
            if d == (0, -1): out[v] = (x, cy - z, y - cy)
        return out
    def go(c, pos):
        seen.add(c); bot = [v for v, p in pos.items() if p[2] == 0]
        assert len(bot) == 4
        for v in bot:
            pt = pos[v][:2]
            assert mp.get(pt, v) == v, '折りたたみで同じ点が2つの頂点になった'
            mp[pt] = v
        for d in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (c[0] + d[0], c[1] + d[1])
            if n in S and n not in seen: go(n, T(pos, c, d))
    c0 = cells[0]
    go(c0, {(a, b, z): (c0[0] + a, c0[1] + b, z) for a in (0, 1) for b in (0, 1) for z in (0, 1)})
    assert len(seen) == 6 and len(set(mp.values())) == 8
    return mp


class Net:
    def __init__(self, cells):
        self.cells = cells; self.mp = fold_vertices(cells)
        pts = sorted(self.mp, key=lambda p: (-p[1], p[0]))
        self.L = {p: chr(65 + i) for i, p in enumerate(pts)}; self.P = {v: k for k, v in self.L.items()}
        self.V = {v: v for v in self.mp.values()}

    def same(self, a):
        """点 a と重なる点（自分はのぞく）"""
        v = self.mp[self.P[a]]
        return sorted(self.L[p] for p in self.mp if self.mp[p] == v and self.L[p] != a)

    def edge(self, s): return (self.mp[self.P[s[0]]], self.mp[self.P[s[1]]])

    def rel(self, s, t): return line_rel(self.V, self.edge(s), self.edge(t))

    def fig(self):
        xs = [c[0] for c in self.cells]; ys = [c[1] for c in self.cells]
        fg = Fig(min(xs) - 0.5, max(xs) + 1.5, min(ys) - 0.5, max(ys) + 1.5, px=280)
        for (x, y) in self.cells: fg.poly((x, y), (x + 1, y), (x + 1, y + 1), (x, y + 1))
        S = set(self.cells)
        for p, n in self.L.items():
            quads = [((1, 1), (p[0], p[1])), ((-1, 1), (p[0] - 1, p[1])), ((-1, -1), (p[0] - 1, p[1] - 1)), ((1, -1), (p[0], p[1] - 1))]
            free = [q for q, c in quads if c not in S] or [q for q, c in quads]
            ux, uy = free[0]
            fg.point(n, p, off=(ux, -uy), d=13)
        return fg


