def lattice_paths(nx, ny, nz):
    from functools import lru_cache
    @lru_cache(None)
    def f(x, y, z):
        if (x, y, z) == (0, 0, 0): return 1
        return sum(f(*p) for p in ((x - 1, y, z), (x, y - 1, z), (x, y, z - 1)) if min(p) >= 0)
    return f(nx, ny, nz)
