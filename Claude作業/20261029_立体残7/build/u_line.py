def cross(u, v): return u[0] * v[1] - u[1] * v[0]
def vec(p, q): return (q[0] - p[0], q[1] - p[1])
def dot(u, v): return u[0] * v[0] + u[1] * v[1]
def gseg(fg, name, p, q, dx=0, dy=0):
    """線分と名前。名前は線分のまん中から、線分に垂直な向き（上側）へ 15px はなす"""
    fg.seg(p, q); vx, vy = q[0] - p[0], q[1] - p[1]; L = math.hypot(vx, vy); nx, ny = -vy / L, vx / L
    if ny < 0: nx, ny = -nx, -ny
    fg.text(name, ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2), dx=nx * 15, dy=-ny * 15)

