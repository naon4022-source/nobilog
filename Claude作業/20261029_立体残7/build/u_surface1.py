def ell(fg, c, rx, ry, a0=0, a1=360, dash=False, n=48):
    pts = [(c[0] + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), c[1] + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]
    fg.el.append('<polyline' + (' stroke-dasharray="5 4"' if dash else '') + ' points="' + ' '.join('%.1f,%.1f' % fg.T(p) for p in pts) + '"/>')
def cylinder(fg, cx, y0, r, h, k=0.32):
    ell(fg, (cx, y0 + h), r, r * k); ell(fg, (cx, y0), r, r * k, 180, 360); ell(fg, (cx, y0), r, r * k, 0, 180, dash=True)
    fg.seg((cx - r, y0), (cx - r, y0 + h)); fg.seg((cx + r, y0), (cx + r, y0 + h))
def cone(fg, cx, y0, r, h, k=0.32):
    ell(fg, (cx, y0), r, r * k, 180, 360); ell(fg, (cx, y0), r, r * k, 0, 180, dash=True)
    fg.seg((cx - r, y0), (cx, y0 + h)); fg.seg((cx + r, y0), (cx, y0 + h))
def expr_units(q): q['answer']['units'] = S2; return q

