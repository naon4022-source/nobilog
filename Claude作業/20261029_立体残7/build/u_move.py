def rot(p, c, deg):
    t = math.radians(deg); x, y = p[0] - c[0], p[1] - c[1]
    return (round(c[0] + x * math.cos(t) - y * math.sin(t), 9) + 0.0, round(c[1] + x * math.sin(t) + y * math.cos(t), 9) + 0.0)
def rx(p, k): return (2 * k - p[0], p[1])      # 直線 x ＝ k について対称移動
def ry(p, k): return (p[0], 2 * k - p[1])      # 直線 y ＝ k について対称移動
def tr(p, v): return (p[0] + v[0], p[1] + v[1])
def P(x, y): return pt(F(x).limit_denominator(1000), F(y).limit_denominator(1000))
def axes(fg, x0, x1, y0, y1):
    fg.grid(x0, x1, y0, y1); fg.seg((x0, 0), (x1, 0)); fg.seg((0, y0), (0, y1))
    fg.text('x', (x1, 0), dx=-6, dy=13); fg.text('y', (0, y1), dx=12, dy=6); fg.text('O', (0, 0), dx=-10, dy=12)
def tri(fg, names, pts, offs):
    fg.poly(*pts)
    for n, p, o in zip(names, pts, offs): fg.point(n, p, off=o)

