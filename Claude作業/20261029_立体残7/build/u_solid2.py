def arc(c, r, d1, d2, n=48): return [(c[0] + r * math.cos(math.radians(d1 + (d2 - d1) * i / n)), c[1] + r * math.sin(math.radians(d1 + (d2 - d1) * i / n))) for i in range(n + 1)]
