import statistics as st
def S(x):
    x = F(x)
    if x.denominator == 1: return str(x.numerator)
    t = F(str(round(x.numerator / x.denominator, 6)))
    assert t == x, ('割り切れない', x)
    return str(round(x.numerator / x.denominator, 6)).rstrip('0').rstrip('.')
def T(head, lows, w, fs, unit='人'):
    return head + '\n' + '\n'.join(f'{S(lo)} 以上 {S(lo + w)} 未満：{f} {unit}' for lo, f in zip(lows, fs))
def cvs(lows, w): return [F(lo) + F(w) / 2 for lo in lows]
def tmean(lows, w, fs):  # 作問用：Σ(階級値×度数)÷Σ度数
    return sum(c * f for c, f in zip(cvs(lows, w), fs)) / sum(fs)
def emean(lows, w, fs):  # 検算用：階級値をならべた資料の平均（statistics）
    return F(st.mean([c for c, f in zip(cvs(lows, w), fs) for _ in range(f)]))
def mclass(lows, w, fs):  # 検算用：中央値のはいる階級の階級値（並べた資料から）
    d = [c for c, f in zip(cvs(lows, w), fs) for _ in range(f)]
    n = len(d); a, b = d[(n - 1) // 2], d[n // 2]
    assert a == b, '中央値が2つの階級にまたがる'
    return a
def modecv(lows, w, fs):
    m = max(fs); assert fs.count(m) == 1; return cvs(lows, w)[fs.index(m)]
def EX(lows, w, fs, unit=''):
    c = cvs(lows, w)
    terms = ' + '.join(f'{S(ci)} × {f}' for ci, f in zip(c, fs))
    tot = sum(ci * f for ci, f in zip(c, fs))
    return f'①階級値は {"、".join(S(ci) for ci in c)}　②{terms} ＝ {S(tot)}　③{S(tot)} ÷ {sum(fs)} ＝ {S(tot / sum(fs))}。答え {S(tot / sum(fs))}{unit}'

