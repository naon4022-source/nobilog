def isp(n): return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))
def divs(n): return [d for d in range(1, abs(n) + 1) if n % d == 0]
def pf(n):
    out, d = [], 2
    while n > 1:
        while n % d == 0: out.append(d); n //= d
        d += 1
    return out
def lcm(a, b): return a * b // gcd(a, b)
