"""特訓：立体の表面積①（教科書 p208〜210：角柱・円柱・角錐・円錐の表面積）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('surface1', '教科書 p208〜210（表面積・側面積・円錐の展開図）',
         '2026-10-08 Claude作成（特訓・下書き）。表面積と円錐の展開図を、逆に求める・立体を組み合わせる・切り分けるなどに広げた一段難しい問題。答えは check.py で計算し直して検算。'
         '【保留】図なしで伝えられ、教科書問題と似ない問題は 7 問まで。70問にしていない。')
Q = [F(n, 10) for n in range(0, 5001)]

U.num('立方体の体積が 64 cm³ のとき、表面積を求めよう。', '96',
      '①1辺 4 cm（4 × 4 × 4 ＝ 64）　②1つの面 16 cm² が 6 面　③96。答え 96cm²',
      lambda: only(6 * a * a for a in Q if a > 0 and a ** 3 == 64), units=['cm²'])
U.num('底面の半径が 3 cm の円柱の側面積が 30π cm² である。高さを求めよう。', '5',
      '①側面は、横が底面の円周 6π、縦が高さの長方形　②6π × h ＝ 30π　③h ＝ 5。答え 5cm',
      lambda: only(h for h in Q if 6 * h == 30), units=['cm'])
U.num('母線の長さが 10 cm、底面の半径が 4 cm の円錐の展開図で、側面のおうぎ形の中心角を求めよう。', '144',
      '①おうぎ形の弧 ＝ 底面の円周 8π　②半径 10 の円周 20π との比 8/20 ＝ 2/5　③360 × (2/5) ＝ 144。答え 144度',
      lambda: only(a for a in Q if F(a, 360) * 20 == 8), units=['度', '°'])
U.num('円錐の展開図で、側面のおうぎ形の半径（母線）が 9 cm、中心角が 120° である。底面の円の半径を求めよう。', '3',
      '①おうぎ形の弧 ＝ 2π × 9 × (120/360) ＝ 6π　②底面の円周 2πr ＝ 6π　③r ＝ 3。答え 3cm',
      lambda: only(r for r in Q if 2 * r == 2 * 9 * F(120, 360)), units=['cm'])
U.expr('母線の長さ 6 cm、底面の半径 2 cm の円錐の表面積を、π を使って答えよう（cm²）。', '16π',
       '①側面のおうぎ形：半径 6、弧 4π で、面積 4π × 6 ÷ 2 ＝ 12π　②底面 π × 4 ＝ 4π　③16π。答え 16π cm²',
       lambda π: 4 * π * 6 / 2 + π * 4)
U.num('1辺 1 cm の立方体を 8 個すき間なく積んで、1辺 2 cm の立方体をつくった。この立方体の表面積は、8 個をばらばらにしたときの表面積の合計の何倍か答えよう。', '1/2',
      '①大きい立方体 6 × 4 ＝ 24 cm²　②ばらばら 6 × 8 ＝ 48 cm²　③24/48 ＝ 1/2。答え 1/2倍',
      lambda: F(6 * 2 * 2, 6 * 8), units=['倍'])
U.expr('底面の半径が 4 cm の円柱を、底面に平行な平面で2つに切ると、2つの円柱の表面積の和は、もとの円柱より何 cm² ふえるか。π を使って答えよう。', '32π',
       '①切り口の円が2つふえる　②π × 16 × 2 ＝ 32π　③答え 32π cm²',
       lambda π: 2 * π * 16)
