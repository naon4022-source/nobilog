"""特訓：ヒストグラムと相対度数②（教科書 p227〜231：代表値・相対度数・累積相対度数）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('hist2', '教科書 p227〜231（代表値・相対度数）',
         '2026-10-08 Claude作成（特訓・下書き）。代表値・相対度数を、逆に求める・2つの集団を合わせるなどに広げた一段難しい問題。答えは check.py で計算し直して検算。'
         '【保留】教科書問題と似ない考え方の問題は 5 問まで。70問にしていない。')
U.num('5つのデータ 3、7、x、10、12 の平均値が 9 である。x の値を答えよう。', '13',
      '①合計は 9 × 5 ＝ 45　②3 + 7 + 10 + 12 ＝ 32　③x ＝ 45 − 32 ＝ 13。答え 13',
      lambda: only(x for x in range(0, 100) if F(3 + 7 + x + 10 + 12, 5) == 9))
U.num('4つのデータ 2、5、9、x（x は 9 より大きい）の中央値と平均値が等しい。x の値を答えよう。', '12',
      '①小さい順に 2、5、9、x で、中央値は (5 + 9) ÷ 2 ＝ 7　②平均値 (16 + x) ÷ 4 ＝ 7　③x ＝ 12。答え 12',
      lambda: only(x for x in range(10, 100) if F(5 + 9, 2) == F(2 + 5 + 9 + x, 4)))
U.num('40 人のデータで、ある階級の相対度数が 0.35 だった。その階級の度数を答えよう。', '14',
      '①度数 ＝ 相対度数 × 度数の合計　②0.35 × 40 ＝ 14　③答え 14人',
      lambda: F(35, 100) * 40, units=['人'])
U.num('25 人のデータで、ある階級までの累積相対度数が 0.6 だった。その階級までの人数を答えよう。', '15',
      '①累積相対度数 ＝ 累積度数 ÷ 全体　②0.6 × 25 ＝ 15　③答え 15人',
      lambda: F(6, 10) * 25, units=['人'])
U.num('A組 20 人とB組 30 人のデータで、ある階級の相対度数は、A組が 0.25、B組が 0.2 だった。2つの組を合わせた 50 人での、その階級の相対度数を求めよう。', '0.22',
      '①A組の度数 0.25 × 20 ＝ 5、B組 0.2 × 30 ＝ 6　②合わせて 11 人　③11 ÷ 50 ＝ 0.22（相対度数どうしの平均 0.225 ではない）。答え 0.22',
      lambda: (F(25, 100) * 20 + F(2, 10) * 30) / 50)
