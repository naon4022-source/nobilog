"""特訓：いろいろな立体①（教科書 p184〜189：角柱・角錐・多面体・正多面体）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('solid1', '教科書 p184〜189（多面体と正多面体）',
         '2026-10-08 Claude作成（特訓・下書き）。頂点・辺・面の数を、逆に求める・面の形から数える・切り落とした立体などに広げた一段難しい問題。答えは check.py で数え直して検算。'
         '【保留】図なしで伝えられ、教科書問題（○角柱の辺の数など）と似ない問題は 8 問まで。70問にしていない。')

U.num('七角柱の頂点の数、辺の数、面の数をすべてたした和を求めよう。', '44',
      '①n 角柱は 頂点 2n、辺 3n、面 n + 2　②n ＝ 7：14 + 21 + 9　③44。答え 44',
      lambda: 2 * 7 + 3 * 7 + (7 + 2))
U.num('辺の数が 16 本の角錐がある。この角錐の面の数を答えよう。', '9',
      '①n 角錐の辺は 2n 本なので 2n ＝ 16、n ＝ 8（八角錐）　②面は底面 1 + 側面 8　③9。答え 9',
      lambda: only(n + 1 for n in range(3, 50) if 2 * n == 16))
U.num('正二十面体は、20 個の正三角形の面でできていて、1つの頂点に 5 つの面が集まっている。頂点の数を答えよう。', '12',
      '①正三角形 20 個の頂点は全部で 20 × 3 ＝ 60 個分　②1つの頂点に 5 つの面が集まるので 60 ÷ 5　③12。答え 12',
      lambda: F(20 * 3, 5))
U.num('正十二面体は、12 個の正五角形の面でできている。辺の数を答えよう。', '30',
      '①正五角形 12 個の辺は 12 × 5 ＝ 60 本分　②1本の辺は2つの面で共有されるので 60 ÷ 2　③30。答え 30',
      lambda: F(12 * 5, 2))
U.num('頂点が 10 個、面が 7 個の多面体がある。辺の数を答えよう（多面体では「頂点の数 − 辺の数 + 面の数 ＝ 2」が成り立つ）。', '15',
      '①10 − 辺 + 7 ＝ 2　②辺 ＝ 15　③答え 15（例：五角柱）',
      lambda: only(e for e in range(0, 100) if 10 - e + 7 == 2))
U.num('面の数が 12 個の角柱がある。この角柱の辺の数を答えよう。', '30',
      '①n 角柱の面は n + 2 なので n ＝ 10　②辺は 3n ＝ 30　③答え 30',
      lambda: only(3 * n for n in range(3, 50) if n + 2 == 12))
U.num('サッカーボールの形の多面体は、正五角形 12 個と正六角形 20 個の面でできている。辺の数を答えよう。', '90',
      '①辺は全部で 12 × 5 + 20 × 6 ＝ 180 本分　②1本の辺は2つの面で共有されるので 180 ÷ 2　③90。答え 90',
      lambda: F(12 * 5 + 20 * 6, 2))
U.num('立方体の 8 つのかどを、それぞれ小さな三角錐の形に切り落とした（切り口は三角形で、切り口どうしは重ならない）。できた立体の頂点の数を答えよう。', '24',
      '①かど1つを切り落とすと、もとの頂点1つが消え、切り口の三角形の頂点 3 つができる　②8 × 3 ＝ 24　③答え 24',
      lambda: 8 * 3)
