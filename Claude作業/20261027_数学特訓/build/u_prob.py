"""特訓：データにもとづく確率（教科書 p239〜243）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('prob', '教科書 p239〜243（相対度数と確率）',
         '2026-10-08 Claude作成（特訓・下書き）。相対度数を確率として使い、回数や個数を予想する一段難しい問題。答えは check.py で計算し直して検算。'
         '【保留】教科書問題と似ない考え方の問題は 5 問まで。70問にしていない。')
U.num('あるびんのふたを 2000 回投げたら、表が 760 回出た。このふたを 3000 回投げると、表はおよそ何回出ると考えられるか答えよう。', '1140',
      '①表の出る確率はおよそ 760 ÷ 2000 ＝ 0.38　②3000 × 0.38 ＝ 1140　③答え およそ 1140回',
      lambda: F(760, 2000) * 3000, units=['回'])
U.num('画びょうを投げて上向きになった回数は、200 回で 82 回、400 回で 158 回、600 回で 241 回、800 回で 320 回だった。上向きになる確率はどのくらいと考えられるか、小数第2位までで答えよう。', '0.40',
      '①相対度数は 0.41、0.395、0.401…、0.40 と、回数がふえると 0.40 に近づく　②回数がもっとも多い 800 回の値を使う　③答え 0.40',
      lambda: F(320, 800))
U.num('袋の中に白玉と黒玉が合わせて 100 個ある。よくかき混ぜて1個取り出し、色を調べてもどすことを 50 回くり返したら、白玉が 18 回出た。袋の中の白玉はおよそ何個と考えられるか答えよう。', '36',
      '①白玉の出る確率はおよそ 18 ÷ 50 ＝ 0.36　②100 × 0.36 ＝ 36　③答え およそ 36個',
      lambda: F(18, 50) * 100, units=['個'])
U.num('池の魚の数を調べる。50 ぴきをつかまえて印をつけて池にもどし、しばらくして 60 ぴきをつかまえたら、そのうち 12 ひきに印がついていた。池の魚はおよそ何びきと考えられるか答えよう。', '250',
      '①印のついた魚の割合はおよそ 12 ÷ 60 ＝ 1/5　②池全体でも 50 ぴきが 1/5 にあたると考える　③50 × 5 ＝ 250。答え およそ 250ぴき',
      lambda: only(n for n in range(50, 2000) if F(50, n) == F(12, 60)), units=['ひき', '匹'])
U.num('あることがらの起こる確率が 0.25 と考えられるとき、そのことがらが起こらない確率はどのくらいと考えられるか答えよう。', '0.75',
      '①起こる場合と起こらない場合の相対度数の和は 1　②1 − 0.25 ＝ 0.75　③答え 0.75',
      lambda: 1 - F(1, 4))
