"""特訓：ヒストグラムと相対度数①（教科書 p224〜227：範囲・度数分布表・累積度数・ヒストグラム）。"""
from fractions import Fraction as F
from mk import Unit
from vutil import only

U = Unit('hist1', '教科書 p224〜227（範囲・度数分布表・ヒストグラム）',
         '2026-10-08 Claude作成（特訓・下書き）。度数分布表とヒストグラムを、逆にたどる・条件から値を決める問題に広げた一段難しい問題。答えは check.py で数え直して検算。'
         '【保留】教科書問題と似ない考え方の問題は 4 問まで。70問にしていない。')
D = [12, 15, 7, 20, 18, 9, 14]
U.num('7つのデータ 12、15、7、20、18、9、14 に、20 より大きい値 x を1つ加えたら、範囲が 15 になった。x の値を答えよう。', '22',
      '①範囲 ＝ 最大値 − 最小値　②最小値は 7 のままなので、最大値 x − 7 ＝ 15　③x ＝ 22。答え 22',
      lambda: only(x for x in range(21, 100) if max(D + [x]) - min(D + [x]) == 15))
U.num('ある度数分布表の累積度数が、小さい階級から順に 3、8、15、18、20 である。3番目の階級の度数を答えよう。', '7',
      '①累積度数は、その階級までの度数の合計　②3番目の度数 ＝ 15 − 8　③7。答え 7',
      lambda: [3, 8, 15, 18, 20][2] - [3, 8, 15, 18, 20][1])
U.num('階級の幅が 5 cm のヒストグラムで、度数の合計は 30 人である。ヒストグラムの長方形の面積をすべてたすと、いくつになるか答えよう（横は cm、縦は人の目もりで考える）。', '150',
      '①長方形1つの面積 ＝ 階級の幅 × 度数　②合計 ＝ 5 × (度数の合計) ＝ 5 × 30　③150。答え 150',
      lambda: 5 * 30)
U.num('20 人のデータの最小値は 10、最大値は 37 である。8 以上 12 未満から始めて、階級の幅 4 で度数分布表をつくると、階級はいくつ必要か答えよう。', '8',
      '①階級：8〜12、12〜16、…と 4 ずつ　②37 がはいるのは 36 以上 40 未満　③8〜12 から 36〜40 まで (40 − 8) ÷ 4 ＝ 8 個。答え 8',
      lambda: only(n for n in range(1, 30) if 8 + 4 * (n - 1) <= 37 < 8 + 4 * n))
