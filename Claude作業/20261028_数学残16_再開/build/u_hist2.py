def S(x):
    x = F(x)
    if x.denominator == 1: return str(x.numerator)
    t = x.numerator / x.denominator
    return (str(round(t, 4)).rstrip('0').rstrip('.')) if F(str(round(t, 4))) == x else f'{x.numerator}/{x.denominator}'
def med(d):
    d = sorted(d); n = len(d)
    return F(d[n // 2]) if n % 2 else F(d[n // 2 - 1] + d[n // 2], 2)
def mean(d): return F(sum(F(v) for v in d), len(d))
def mode(d):
    c = {v: d.count(v) for v in d}; m = max(c.values()); ks = [k for k, v in c.items() if v == m]
    assert len(ks) == 1; return ks[0]
