def poly(ps):
    s = 0
    for (x1, y1), (x2, y2) in zip(ps, ps[1:] + ps[:1]): s += F(x1) * y2 - F(x2) * y1
    return abs(s) / 2
def mv(p, dx, dy): return (p[0] + dx, p[1] + dy)
def rot90(p): return (-p[1], p[0])

