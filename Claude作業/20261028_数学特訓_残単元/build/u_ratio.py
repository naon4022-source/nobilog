from math import gcd
def simple(*xs):
    d = 1
    for k in range(2, 1000):
        if all((x * k).denominator == 1 for x in xs): d = k; break
    ns = [int(x * d) for x in xs]; g = 0
    for n in ns: g = gcd(g, n)
    return '：'.join(str(n // g) for n in ns)
def wordratio(s): return [s, s.replace('：', ':')]

