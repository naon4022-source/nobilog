def paren_values(nums, ops):
    """数と演算の並びに、かっこを1組つける（つけない場合もふくむ）すべての値"""
    out = []
    n = len(nums)
    for i in range(n):
        for j in range(i, n):
            s = ''
            for k in range(n):
                if k == i: s += '('
                s += f'F({nums[k]})'
                if k == j: s += ')'
                if k < n - 1: s += ops[k]
            out.append(eval(s))
    return out


