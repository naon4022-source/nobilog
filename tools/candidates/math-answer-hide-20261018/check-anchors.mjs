import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {webcrypto} from 'node:crypto';
import vm from 'node:vm';
const root=new URL('../../../',import.meta.url),here=new URL('./',import.meta.url);
const context=vm.createContext({crypto:webcrypto,TextEncoder});
vm.runInContext(await readFile(new URL('site-assets/textbook-annotation-model.js',root),'utf8'),context);
const before=JSON.parse(await readFile(new URL('previous/textbook-book-math1.json',here),'utf8'));
const after=JSON.parse(await readFile(new URL((process.argv.includes('--final')?'out-final/':'out/')+'textbook-book-math1.json',here),'utf8'));
const model=context.NobiTextbookAnnotationModel;
const [old,now]=await Promise.all([model.prepare(before,'math1'),model.prepare(after,'math1')]);
const anchors=data=>data.pages.flatMap(p=>(p.blocks||[]).filter(b=>b.annotationAnchor).map(b=>({anchor:b.annotationAnchor,quote:b.annotationQuote,pid:p.pid})));
const a=JSON.parse(JSON.stringify(anchors(old.data))),b=JSON.parse(JSON.stringify(anchors(now.data)));
assert.deepEqual(a,b,'all existing marker/note anchors and quoted text retain exactly the same identity');
assert.notEqual(old.signature,now.signature,'new content invalidates annotated layout cache');
assert.equal(before.pageCount,after.pageCount,'source pages retain their identity');
assert.deepEqual(before.toc,after.toc,'source TOC links unchanged; physical page destinations calculated by existing paginator');
assert.equal(before.pages.length,after.pages.length);
const result={status:'passed',anchors:a.length,sourcePages:before.pages.length,unchangedAnchorsAndQuotes:true,signatureChanged:true,scope:'Actual annotation model on old/new教材 only; no real saved records loaded or modified.'};
await writeFile(new URL('annotation-result.json',here),JSON.stringify(result,null,2)+'\n');
console.log(a.length+' real-model annotation anchors/quotes unchanged across '+before.pages.length+' source pages; old notes are not rebound to different text, layout signature refreshed. No user data.');
