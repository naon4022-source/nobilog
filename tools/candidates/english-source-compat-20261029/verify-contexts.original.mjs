import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {publicContextIndex,build,BOOKS} from './build-contexts.mjs';

const ROOT=new URL('../../../',import.meta.url),sha=x=>createHash('sha256').update(x).digest('hex');
const require=createRequire(import.meta.url);
const {checkedSource:checkedExplanationSource}=require('../textbook-final-20261023/explanations-20261025/checked-source.cjs');
const {checkMainSource}=require('../textbook-vision-20261027/main/checked-source.cjs');
// Validate the entire exact teaching successor before comparing historical source identity.
const approvedBefore=checkMainSource(require('node:url').fileURLToPath(ROOT),{assets:false});
const checkedSource=relative=>approvedBefore.get(relative)||checkedExplanationSource(relative);
let checks=0;const ok=(value,message)=>{assert.ok(value,message);checks++;};
const hidden='PRIVATE_ANSWER_SENTINEL',privateRoot='PRIVATE_RECORD_SENTINEL';
const publicBlock={t:'p',x:'**公開本文**を選んで、考え方を確かめる。'};
const fixture={id:'math1',title:'合成教科書',subject:'数学',privateRecord:privateRoot,pages:[{n:1,chapter:'合成1章',section:'合成1節',sectionTitle:'選択の確認',blocks:[
 publicBlock,
 {t:'details',summary:'答え',body:[{t:'p',x:hidden,annotationAnchor:'a'.repeat(64),annotationQuote:hidden},{t:'details',body:[{t:'p',x:hidden+' nested'}]}]},
 {t:'table',answer:hidden,rows:[[hidden]]},
 {t:'p',x:'後ろの公開本文。',answer:hidden},
]}]};
const raw=JSON.stringify(fixture),result=await publicContextIndex('math1',raw),wire=JSON.stringify(result.value);
ok(JSON.stringify(fixture)===raw,'source object is not mutated');
ok(result.value.contexts.length===2,'only public annotated source blocks are indexed');
ok(!wire.includes(hidden)&&!wire.includes(privateRoot),'closed nested/legacy answers and unrelated fields never enter public index');
ok(result.value.contexts[0].anchor===sha('math1:1:0:'+JSON.stringify(publicBlock)),'identity matches existing original-source anchor contract');
ok(result.value.contexts[0].quote==='公開本文を選んで、考え方を確かめる。','quote matches marker plain text');
ok(result.value.contexts[1].page===1&&result.value.sourceSha256===sha(raw),'source page and raw source SHA are bound');
ok(result.sha256===sha(result.bytes),'generated bytes are bound independently');
async function reject(name,book,value){await assert.rejects(()=>publicContextIndex(book,JSON.stringify(value)));checks++;}
await reject('unknown book','../math1',fixture);
await reject('wrong book identity','english1',fixture);
await reject('no public excerpt','math1',{...fixture,pages:[{n:1,blocks:[fixture.pages[0].blocks[1]]}]});
await reject('duplicate source page','math1',{...fixture,pages:[fixture.pages[0],fixture.pages[0]]});
await reject('unknown blockless source page','math1',{...fixture,pages:[{n:1,kind:'unknown'}]});
await reject('heading control character','math1',{...fixture,pages:[{...fixture.pages[0],chapter:'bad\u0000heading'}]});
const duplicate={t:'p',x:'同じ公開箇所',annotationAnchor:'b'.repeat(64),annotationQuote:'同じ公開箇所'};
await reject('ambiguous inherited public identity','math1',{...fixture,pages:[{n:1,blocks:[duplicate,duplicate]}]});
const capped=await publicContextIndex('math1',JSON.stringify({...fixture,pages:[{n:1,blocks:[{t:'p',x:'あ'.repeat(2500)}]}]}));
ok(capped.value.contexts[0].quote.length===2000,'marker excerpt cap is retained');
const wrappers=await publicContextIndex('math1',JSON.stringify({...fixture,pages:[{n:1,kind:'cover'},{n:2,kind:'toc'},{n:3,kind:'guide'},{...fixture.pages[0],n:4},{n:5,kind:'end'}]}));
ok(wrappers.value.contexts.length===2&&wrappers.value.contexts.every(c=>c.page===4),'existing blockless cover/toc/guide/end never become excerpts');

const baseline=JSON.parse(await readFile(new URL('./baseline.json',import.meta.url),'utf8'));
const actual=await build('--check');
ok(actual.outputs.length===7,'six context assets plus one fixed manifest; check mode has no writes');
const privateAnchorCounts={};
for(const book of BOOKS){
 const source=await readFile(new URL(baseline.sourceBooks[book].file,ROOT));
 ok(sha(checkedSource(baseline.sourceBooks[book].file))===baseline.sourceBooks[book].sha256,book+': source preserved except exact separately approved explanations');
 const generated=JSON.parse(await readFile(new URL('site-assets/textbook-ai-context-'+book+'.json',ROOT),'utf8'));
 ok(generated.contexts.length===actual.books[book].count&&generated.contexts.every(c=>Object.keys(c).sort().join(',')==='anchor,chapter,kind,page,quote,section,sectionTitle'),book+': exact public fields only');
 const pages=JSON.parse(source).pages,byPage=new Map(pages.map(p=>[p.n,p])),closedIds=new Set();
 function closed(blocks,inside=false){for(const b of blocks||[]){if(inside&&typeof b.annotationAnchor==='string')closedIds.add(b.annotationAnchor);if(b.t==='details')closed(b.body,true);}}
 for(const p of pages)closed(p.blocks);
 privateAnchorCounts[book]=closedIds.size;
 ok(generated.contexts.every(c=>!closedIds.has(c.anchor)),book+': no inherited closed-answer source identity in public index');
 ok(generated.contexts.every(c=>{const p=byPage.get(c.page);return p&&c.chapter===(p.chapter||'')&&c.section===(p.section||'')&&c.sectionTitle===(p.sectionTitle||'');}),book+': all context locations match the actual source page');
}
console.log(JSON.stringify({status:'passed',checks,books:actual.books,privateAnchorCounts,scope:'source identity/public excerpt generation only; no AI integration, provider calls or real data; no closed details included'},null,2));
