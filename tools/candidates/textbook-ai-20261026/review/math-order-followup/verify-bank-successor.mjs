import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {reviewedMathBankSuccessor} from './checked-bank-successor.mjs';
const here=new URL('./',import.meta.url);
const before=JSON.parse(await readFile(new URL('main-before/site-assets/material-bank.json',here)));
const current=JSON.parse(await readFile(new URL('../../../../../site-assets/material-bank.json',here)));
let checks=0;
assert.deepEqual(await reviewedMathBankSuccessor(before,current),current);checks++;
const alteredAnswer=structuredClone(before);
alteredAnswer.units.find(u=>u.id==='workbook-math-1-calc1').questions[0].answer={type:'exact',value:'tampered'};
await assert.rejects(()=>reviewedMathBankSuccessor(alteredAnswer,current),/exact approved predecessor/);checks++;
const alteredCurrent=structuredClone(current);
alteredCurrent.units.find(u=>u.id==='workbook-math-1-calc1').questions[0].prompt+=' tampered';
await assert.rejects(()=>reviewedMathBankSuccessor(before,alteredCurrent),/actual current bank/);checks++;
const unrelated=structuredClone(before);
unrelated.sources[0].title='unapproved source change';
const transformed=await reviewedMathBankSuccessor(unrelated,current);
assert.equal(transformed.sources[0].title,'unapproved source change');checks++;
assert.notDeepEqual(transformed,current,'unapproved source change remains detectable by the original full comparison');checks++;
await writeFile(new URL('bank-successor-result.json',here),JSON.stringify({status:'passed',checks,scope:'Exact pinned nine-file math correction and three frozen independent proofs. Wrong historical answer/current prompt rejected; unrelated source changes remain visible to the original deep comparison. No app code, provider or learner record changes.'},null,2)+'\n');
console.log('Historical math successor:',checks,'strict preservation and mutation checks passed');
