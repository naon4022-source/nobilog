def pi(c, const=0):
    """cπ ＋ const の採点用の文字列"""
    c, const = F(c), F(const)
    s = ('' if c == 1 else ('-' if c == -1 else ans_str(c))) + 'π' if c else ''
    if const: s += (('+' if const > 0 else '-') if s else ('' if const > 0 else '-')) + ans_str(abs(const))
    return s or '0'
def pid(c, const=0):
    """表示用"""
    c, const = F(c), F(const)
    s = ('' if c == 1 else fx(c)) + 'π' if c else ''
    if const: s += ((' ＋ ' if const > 0 else ' − ') if s else ('' if const > 0 else '−')) + fx(abs(const))
    return s or '0'
